/**
 * Execute any MTProto RPC call by method name with genuine wire protocol dispatch.
 */
export async function dispatchMtprotoRpc(
  client: MtprotoCallableClient,
  method: string,
  params: any = {}
): Promise<any> {
  const caller = MTPROTO_RPC_CALLERS[method]
  if (!caller) {
    // Fallback: direct dynamic call for any novel or custom constructor
    return client.call({ _: method, ...params })
  }
  return caller(client, params)
}
