export interface AccountAgeEstimation {
  timestamp: number
  date: Date
  formattedDate: string // e.g. "March 2021" / "اسفند ۱۳۹۹"
  formattedRelative: string // e.g. "3 years ago" / "۳ سال پیش"
  isOfficialPeerSettings?: boolean
}

/**
 * Estimates Telegram account creation date using binary search and linear interpolation.
 */
export function estimateAccountAge(
  rawUserId: string | number | null | undefined,
  isPersian = false,
  officialRegistrationMonth?: string | null // e.g. "03.2024" from peerSettings
): AccountAgeEstimation | null {
  // If official registration_month from peerSettings (format MM.YYYY) exists:
  if (officialRegistrationMonth && /^\d{1,2}\.\d{4}$/.test(officialRegistrationMonth)) {
    const [monthStr, yearStr] = officialRegistrationMonth.split('.')
    const month = parseInt(monthStr, 10) - 1
    const year = parseInt(yearStr, 10)
    const officialDate = new Date(year, month, 1)
    const now = Date.now()
    const diffMs = Math.max(0, now - officialDate.getTime())

    return {
      timestamp: officialDate.getTime(),
      date: officialDate,
      formattedDate: formatMonthYear(officialDate, isPersian),
      formattedRelative: formatRelativeAge(diffMs, isPersian),
      isOfficialPeerSettings: true,
    }
  }

  if (!rawUserId) return null

  // Clean raw user ID (remove channel/chat prefixes if any)
  const numericStr = String(rawUserId).replace(/^-100|^-/, '')
  const id = Number(numericStr)

  if (isNaN(id) || id <= 0) return null

  const minAnchor = AGE_ANCHORS[0]
  const maxAnchor = AGE_ANCHORS[AGE_ANCHORS.length - 1]

  let estimatedMs: number

  if (id <= minAnchor[0]) {
    estimatedMs = minAnchor[1]
  } else if (id >= maxAnchor[0]) {
    // Extrapolate forward with the slope of the last interval
    const prevAnchor = AGE_ANCHORS[AGE_ANCHORS.length - 2]
    const slope = (maxAnchor[1] - prevAnchor[1]) / (maxAnchor[0] - prevAnchor[0])
    estimatedMs = maxAnchor[1] + (id - maxAnchor[0]) * slope
  } else {
    // Binary search for surrounding anchors
    let low = 0
    let high = AGE_ANCHORS.length - 1

    while (low <= high) {
      const mid = Math.floor((low + high) / 2)
      if (AGE_ANCHORS[mid][0] === id) {
        estimatedMs = AGE_ANCHORS[mid][1]
        break
      } else if (AGE_ANCHORS[mid][0] < id) {
        low = mid + 1
      } else {
        high = mid - 1
      }
    }

    if (estimatedMs! === undefined) {
      // id is between high and low
      const a = AGE_ANCHORS[high]
      const b = AGE_ANCHORS[low]
      const factor = (id - a[0]) / (b[0] - a[0])
      estimatedMs = Math.round(a[1] + factor * (b[1] - a[1]))
    }
  }

  // Telegram was launched in August 2013 (1376438400000)
  const TELEGRAM_LAUNCH_MS = 1376438400000
  if (estimatedMs < TELEGRAM_LAUNCH_MS) {
    estimatedMs = TELEGRAM_LAUNCH_MS
  }

  const date = new Date(estimatedMs)
  const now = Date.now()
  const diffMs = Math.max(0, now - estimatedMs)

  return {
    timestamp: estimatedMs,
    date,
    formattedDate: formatMonthYear(date, isPersian),
    formattedRelative: formatRelativeAge(diffMs, isPersian),
    isOfficialPeerSettings: false,
  }
}

function formatMonthYear(date: Date, isPersian: boolean): string {
  try {
    return date.toLocaleDateString(isPersian ? 'fa-IR' : 'en-US', {
      year: 'numeric',
      month: 'long',
    })
  } catch {
    return date.toDateString()
  }
}

function formatRelativeAge(diffMs: number, isPersian: boolean): string {
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24))
  const years = Math.floor(diffDays / 365)
  const months = Math.floor((diffDays % 365) / 30)

  if (isPersian) {
    if (years > 0 && months > 0) return `حدود ${years} سال و ${months} ماه پیش`
    if (years > 0) return `حدود ${years} سال پیش`
    if (months > 0) return `حدود ${months} ماه پیش`
    return 'به‌تازگی (کمتر از ۱ ماه)'
  }

  if (years > 0 && months > 0) return `~${years} yr ${months} mo ago`
  if (years > 0) return `~${years} yr ago`
  if (months > 0) return `~${months} mo ago`
  return 'Recently (< 1 month)'
}
